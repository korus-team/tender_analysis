def load_icp() -> dict:
    """Активный профиль: из icp_active.json, иначе — ICP по умолчанию."""
    if os.path.exists(ICP_FILE):
        try:
            with open(ICP_FILE, encoding="utf-8") as f:
                data = json.load(f)
            # подстрахуемся: недостающие ключи берём из дефолта
            merged = {**ICP, **data}
            merged["weights"] = {**ICP["weights"], **data.get("weights", {})}
            return merged
        except (json.JSONDecodeError, OSError):
            return ICP
    return ICP


def save_icp(icp: dict) -> None:
    """Сохраняет активный профиль в icp_active.json."""
    with open(ICP_FILE, "w", encoding="utf-8") as f:
        json.dump(icp, f, ensure_ascii=False, indent=2)